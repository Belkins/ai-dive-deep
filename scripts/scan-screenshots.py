#!/usr/bin/env python3
"""Scan public/screens/ and generate src/lib/screenshots.ts with the set of
available screenshot IDs. Run before build (already hooked via npm prebuild).

ID = filename without extension. Supported: .png, .jpg, .jpeg, .webp, .gif, .avif, .svg.

If you drop a new file into public/screens/, re-run `npm run build` and the
ScreenshotPlaceholder component with the matching `id` will swap from
placeholder card to real image automatically.

A GIF can carry a video version: <id>.webm and/or <id>.mp4 beside <id>.gif, and an
optional <id>.poster.<image ext>. Those become VIDEOS[id]; the GIF stays the
SCREENSHOTS entry, and *.poster.* files never become screenshot ids of their own.
"""
import os, json

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCREENS_DIR = os.path.join(REPO_ROOT, 'public', 'screens')
OUT_TS = os.path.join(REPO_ROOT, 'src', 'lib', 'screenshots.ts')

EXTS = {'.png', '.jpg', '.jpeg', '.webp', '.gif', '.avif', '.svg'}
VIDEO_EXTS = ('.webm', '.mp4')  # <source> order
POSTER = '.poster'

def scan(screens_dir):
    """Return (files, videos): id -> image filename, and id -> video sources for GIF ids."""
    files = {}
    names = sorted(e for e in os.listdir(screens_dir) if os.path.isfile(os.path.join(screens_dir, e)))
    for entry in names:
        base, ext = os.path.splitext(entry)
        if ext.lower() in EXTS and not base.endswith(POSTER):
            files[base] = entry  # id -> filename
    videos = {}
    for id_, entry in files.items():
        if not entry.lower().endswith('.gif'):
            continue
        sources = [f'{id_}{v}' for v in VIDEO_EXTS if f'{id_}{v}' in names]
        if not sources:
            continue
        poster = next((n for n in names if os.path.splitext(n)[0] == id_ + POSTER
                       and os.path.splitext(n)[1].lower() in EXTS), None)
        videos[id_] = {'sources': sources, 'poster': poster}
    return files, videos

def main():
    os.makedirs(SCREENS_DIR, exist_ok=True)
    files, videos = scan(SCREENS_DIR)

    js = [
        '// Auto-generated by scripts/scan-screenshots.py — do not edit by hand.',
        '// Re-run via `npm run build` (prebuild hook) when files in public/screens/ change.',
        '',
        '// id (basename without extension) -> filename with extension',
        f'export const SCREENSHOTS: Record<string, string> = {json.dumps(files, indent=2)};',
        '',
        f'export const SCREENSHOT_COUNT = {len(files)};',
        '',
        '// GIF id -> video files that replace it on the page (the GIF stays for old links)',
        f'export const VIDEOS: Record<string, {{ sources: string[]; poster: string | null }}> = {json.dumps(videos, indent=2)};',
    ]
    with open(OUT_TS, 'w') as f:
        f.write('\n'.join(js) + '\n')
    print(f"Wrote {OUT_TS} with {len(files)} screenshot(s).")

if __name__ == '__main__':
    main()
